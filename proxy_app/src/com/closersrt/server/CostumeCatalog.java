    private CostumeCatalog() { }

    private static java.util.Map<Integer, java.util.List<Integer>> byChar;

    private static synchronized void build() {
        if (byChar != null) return;
        byChar = new java.util.HashMap<Integer, java.util.List<Integer>>();
        for (String r : RAW) {
            int a = r.indexOf(124);
            int id = Integer.parseInt(r.substring(0, a));
            int cid = Integer.parseInt(r.substring(a + 1));
            java.util.List<Integer> l = byChar.get(cid);
            if (l == null) { l = new java.util.ArrayList<Integer>(); byChar.put(cid, l); }
            l.add(id);
        }
    }

    /** Costume ids the character actually owns (empty when unknown). */
    public static java.util.List<Integer> forChar(int charId) {
        build();
        java.util.List<Integer> l = byChar.get(charId);
        return l == null ? new java.util.ArrayList<Integer>() : l;
    }

    public static boolean owns(int charId, int costumeId) {
        return forChar(charId).contains(costumeId);
    }
