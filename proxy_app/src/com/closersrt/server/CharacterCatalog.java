    public static String nameOf(int id) {
        String kr = "", zh = "";
        for (String r : RAW) {
            int a = r.indexOf(124);
            int b = r.indexOf(124, a + 1);
            if (Integer.parseInt(r.substring(0, a)) != id) continue;
            kr = r.substring(a + 1, b);
            zh = r.substring(b + 1);
            break;
        }
        if (!zh.isEmpty() && !kr.isEmpty()) return zh + " / " + kr;
        return zh.isEmpty() ? kr : zh;
    }
