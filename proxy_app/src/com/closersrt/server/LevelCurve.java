    private static int[] col(int c) {
        switch (c) {
            case 0: return C0;
            case 1: return C1;
            case 2: return C2;
            default: return C3;
        }
    }

    /**
     * Cumulative EXP needed to BE at `level`.
     *
     * The client subtracts t[level-1] + 1 from the EXP field, so the value we
     * store must be threshold(level) + expWithinLevel.
     */
    public static int threshold(int column, int level) {
        int[] t = col(column);
        if (level <= 1) return 1;
        if (level >= t.length) return t[t.length - 1] + 1;
        return t[level - 1] + 1;
    }

    /** EXP required to advance from `level` to `level + 1`.  Always >= 0. */
    public static int need(int column, int level) {
        int[] t = col(column);
        int last = t.length - 1;
        if (level < 1) return t[Math.min(1, last)];
        if (level >= last) return 0;
        int d = t[level] - t[level - 1];
        return d < 0 ? 0 : d;     // never let a bad row stall a level-up
    }
